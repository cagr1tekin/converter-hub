/**
 * Scans modules/ and writes core/generated-registry.ts.
 *
 * Why codegen instead of a runtime directory scan: Next.js bundles server code
 * ahead of time, so an import() built from a path discovered at runtime cannot
 * be resolved in a production build. Generating static imports keeps the
 * "drop in a folder, change nothing else" workflow while still working under
 * both `next dev` and `next build`. Runs automatically via predev/prebuild.
 */
import { readdirSync, existsSync, writeFileSync, readFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const modulesDir = join(root, "modules");
const outFile = join(root, "core", "generated-registry.ts");

mkdirSync(modulesDir, { recursive: true });

const ids = readdirSync(modulesDir, { withFileTypes: true })
  .filter((e) => e.isDirectory() && existsSync(join(modulesDir, e.name, "module.ts")))
  .map((e) => e.name)
  .sort();

const varName = (id) => "m_" + id.replace(/[^a-zA-Z0-9]/g, "_");

const body = `// AUTO-GENERATED by scripts/gen-registry.mjs — do not edit.
// Re-runs on every \`pnpm dev\` and \`pnpm build\`.
import type { ConverterModule } from "./types";
${ids.map((id) => `import ${varName(id)} from "../modules/${id}/module";`).join("\n")}

export const modules: ConverterModule[] = [
${ids.map((id) => `  ${varName(id)},`).join("\n")}
];
`;

// Avoid rewriting an identical file so the dev server does not reload for nothing.
const prev = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
if (prev !== body) writeFileSync(outFile, body);

console.log(
  ids.length
    ? `[registry] ${ids.length} module: ${ids.join(", ")}`
    : "[registry] modules/ bos"
);
